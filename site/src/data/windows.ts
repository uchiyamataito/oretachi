import raw from './windows.json';

/**
 * 相談窓口の「正本」（single source of truth）
 *
 * ■ なぜこれがあるか
 * 窓口の電話番号・受付時間・注記が、記事とQ&A 29本にベタ書きでコピーされている。
 * そのため「1本を直しても他が古いまま」という事故が繰り返し起きた。2026-08-29時点で5回目：
 *   1. いのちの電話の出典欄が5記事で古いまま（本文だけ直して出典を直し忘れ）
 *   2. DV相談プラスを「24時間／SNS・メールも」と7記事に書いていた（チャットは12:00〜22:00）
 *   3. 「被害・加害どちらの不安についても相談可」に一次ソースが無かった
 *   4. 一括置換で3記事の日本語が壊れた（「受け付けているがある」）
 *   5. 一括置換で3記事に **** が残り、画面に生のアスタリスクが出ていた
 * 危機のときに読む情報でこれが起きている以上、「気をつける」では止まらない。
 *
 * ■ なぜ「共通コンポーネント」ではないのか
 * Content Collections は .md（MDXではない）ため、記事にコンポーネントを埋め込めない。
 * 全記事の文章を機械的に差し替える案も検討したが、29本の窓口ブロックは30種類に分岐していて
 * （記事ごとに文脈に合わせた書き方をしている）、一律の文言に置き換えると読み物として壊れる。
 * そこで **文章は各記事のままにし、「正本と矛盾していないか」を公開前チェックで機械照合する**
 * という設計にした。番号や受付時間を1本でも書き間違えたら npm run check が止める。
 *
 * ■ 実体を .json に置いている理由
 * 最初はこのファイル（.ts）に配列を直接書き、チェッカー側で正規表現で読み取っていた。
 * ところが **コメント行を挟んだ3件（こころの健康相談統一ダイヤル・DV相談プラス・#8008）が
 * 正規表現から外れ、9件中6件しか検査されていなかった**。しかも黙って素通りしていた。
 * 最も事故の多い窓口が検査対象から漏れる、という最悪の壊れ方だったので、
 * データは .json に置き、サイト側もチェッカー側も**同じファイルを import で読む**ことにした。
 * 「設定を人が2箇所に書く」も「片方が構文解析に失敗する」も、構造として起こらないようにする。
 *
 * ■ 更新の手順
 *   1. 一次ソース（公式サイト）を実際に見て windows.json を直す
 *   2. `confirmed` を確認した日付に更新する
 *   3. `npm run check -- --all` を実行し、矛盾する記事を機械に列挙させる
 *   4. 列挙された記事を直す（人が読む文章なので、直すのは人の仕事）
 *
 * ■ 絶対に守ること
 * - 受付時間や料金の注記を「短いから」と省かない。#8008 の通話料や、
 *   いのちの電話のナビダイヤルが有料であることは、かける人にとって実害のある情報。
 * - 一次ソースを見ずに記憶で書き換えない。
 */
export type Window = {
  /** 記事本文に出る表記 */
  name: string;
  /** 電話番号。記事では tel: リンクにする。照合のキーでもある */
  tel: string;
  /** 記事に書くときの受付時間・料金の注記。ここが正本 */
  note: string;
  /** この窓口を書くとき、必ず添える語（省略すると読者が損をする情報） */
  required: string[];
  /** 書いてはいけない表現と、その理由（過去に実際に間違えたもの） */
  forbidden: { phrase: string; why: string }[];
  /** 一次ソース */
  source: string;
  /** 最後に公式サイトで確認した日 */
  confirmed: string;
};

export const WINDOWS: Window[] = raw as Window[];

/** 記事の末尾に必ず添える注記（番号・受付時間は変わりうる、という断り） */
export const WINDOW_DISCLAIMER_PATTERN = /番号[^。]{0,24}変わる|受付[^。]{0,24}変わる/;

/** 番号（ハイフンあり／なし両方）から窓口を引く */
export const WINDOW_BY_TEL: Record<string, Window> = Object.fromEntries(
  WINDOWS.flatMap((w) => [
    [w.tel, w],
    [w.tel.replace(/-/g, ''), w],
  ]),
);
